export type UiMessages = ReturnType<(typeof uiMessages)["resolve"]>["t"];

/** Generic component chrome owned by @k2b/ui, resolved from the inherited render locale. */
export const useUiMessages = (): (() => UiMessages) => {
  const locale = useLocale();
  return () => uiMessages.resolve([locale()]).t;
};

/** Browser-only imperative UI (for example prompts) inherits the document locale. */
export const resolveUiMessages = (locale?: string): UiMessages =>
  uiMessages.resolve([locale ?? (typeof document === "undefined" ? uiMessages.baseLocale : document.documentElement.lang)]).t;

export const checkUiMessages = () => uiMessages.check();
