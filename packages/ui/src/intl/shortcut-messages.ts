/** Imperative UI inherits the document locale when no locale is supplied. */
export const resolveShortcutMessages = (locale?: string) =>
  shortcutMessages.resolve([locale ?? (typeof document === "undefined" ? shortcutMessages.baseLocale : document.documentElement.lang)]).t;
export const checkShortcutMessages = () => shortcutMessages.check();
