export type ChatMessages = ReturnType<(typeof chatMessages)["resolve"]>["t"];

/** Resolved from the inherited render locale. */
export const useChatMessages = (): (() => ChatMessages) => {
  const locale = useLocale();
  return () => chatMessages.resolve([locale()]).t;
};

export const checkChatMessages = () => chatMessages.check();
