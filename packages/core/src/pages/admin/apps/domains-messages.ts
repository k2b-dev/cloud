export type DomainsMessages = ReturnType<typeof domainsMessages.resolve>["t"];

/** The person-facing sentence for one of the domain API's stable error codes. */
export const domainError = (t: DomainsMessages, code: string | undefined): string =>
  ({
    APP_DOMAIN_INVALID_HOST: t.errInvalidHost,
    APP_DOMAIN_CLOUD_HOST: t.errCloudHost,
    APP_DOMAIN_UNKNOWN_APP: t.errUnknownApp,
    APP_DOMAIN_ASSIGNED: t.errAssigned,
    APP_DOMAIN_REDIRECT_TARGET: t.errRedirectTarget,
    APP_DOMAIN_REFERENCED: t.errReferenced,
    APP_DOMAIN_NOT_FOUND: t.errNotFound,
  })[code ?? ""] ?? t.errUnknown;
