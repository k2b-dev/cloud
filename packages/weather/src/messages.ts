export type WeatherMessages = ReturnType<typeof weatherMessages.resolve>["t"];

export const resolveWeatherMessages = (locale: string | undefined) => weatherMessages.resolve(locale ? [locale] : undefined);

export const weatherConditionLabel = (icon: string, t: WeatherMessages): string => {
  switch (icon) {
    case "clear-day":
    case "clear-night":
      return t.conditionClear;
    case "partly-cloudy-day":
    case "partly-cloudy-night":
      return t.conditionPartlyCloudy;
    case "cloudy":
      return t.conditionCloudy;
    case "fog":
      return t.conditionFog;
    case "rain":
      return t.conditionRain;
    case "sleet":
      return t.conditionSleet;
    case "snow":
      return t.conditionSnow;
    case "wind":
      return t.conditionWind;
    case "thunderstorm":
      return t.conditionThunderstorm;
    case "hail":
      return t.conditionHail;
    default:
      return t.conditionCloudy;
  }
};
