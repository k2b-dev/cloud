import { describe, expect, test } from "bun:test";
import { createComponent } from "solid-js";
import { renderToString } from "solid-js/web";
import type { PublicWorkspaceWorkflowRunDetail } from "../workspace/workspace-public-state-model";
import "../ssr-test-plugin";

const { WorkflowRunDetailPanel } = await import("./WorkflowRunDetailPanel");
const { WorkflowRunDocumentsSection } = await import("./WorkflowRunDetailSections");

const detail: PublicWorkspaceWorkflowRunDetail = {
  run: {
    id: "run001",
    workflowId: "wf001",
    launcherId: null,
    baseId: "base01",
    workflowRevision: 1,
    mode: "execute",
    channel: "api",
    actorUserId: null,
    serviceAccountId: null,
    inputs: { note: "Equipment request" },
    status: "running",
    result: null,
    error: null,
    resultMessage: null,
    createdAt: "2026-09-08T10:00:00Z",
    startedAt: "2026-09-08T10:00:00Z",
    finishedAt: null,
  },
  inputLabels: {},
  provenance: { workflowName: "Loans", actorLabel: "Valentin", serviceAccountLabel: null, launcherName: null },
  steps: [],
  stepsTruncated: false,
  documents: { items: [], total: 0, hasMore: false, nextOffset: null },
};

const renderRun = (initialDetail: PublicWorkspaceWorkflowRunDetail | null, level: "read" | "write" = "read") =>
  renderToString(() =>
    createComponent(WorkflowRunDetailPanel, {
      runId: "run001",
      initialDetail,
      workflows: [],
      workflowLevels: { wf001: level },
      liveCursor: null,
      tables: [],
      onRunUpdated: () => {},
      onSelectRun: () => {},
      onClose: () => {},
    }),
  );

describe("a workflow run on v2", () => {
  test("is the detail pane of the runs: its head names the run and its state, its facts who started it and the input", () => {
    const html = renderRun(detail);
    expect(html).toContain('data-k2-part="Pane"');
    expect(html).toContain("data-detail");
    expect(html).toContain('data-scroll-preserve="grids-workflow-run-detail-run001"');
    expect(html).toContain("Run of ");
    expect(html).toContain("Valentin");
    expect(html).toContain("Equipment request");
    // refresh and the rarer deeds wait in "…"; the ID, channel and revision stand under "Technical details"
    expect(html).toContain("More run actions");
    expect(html).toContain("run001");
    expect(html).toContain('data-name="x"');
    expect(html).not.toContain('data-name="repeat"');
    expect(html).not.toContain('data-name="player-stop"');
    expect(html).not.toContain("k2b-detail-panel");
  });

  test("cancels while the run runs and runs again once it ended, for those who may write", () => {
    const running = renderRun(detail, "write");
    expect(running).toContain('data-name="player-stop"');
    expect(running).toContain("Cancel run");
    expect(running).not.toContain(">Run again<");
    const completed = renderRun({ ...detail, run: { ...detail.run, status: "succeeded" } }, "write");
    expect(completed).toContain('data-name="repeat"');
    expect(completed).toContain(">Run again<");
    expect(completed).not.toContain('data-name="player-stop"');
  });

  test("a failed run says why in its head, once", () => {
    const html = renderRun({
      ...detail,
      run: { ...detail.run, status: "failed", error: { code: "step", message: "Customer has no tax number", retryable: false } },
    });
    expect(html.split("Customer has no tax number")).toHaveLength(2);
    expect(html).toContain('data-k2-part="Notice"');
  });

  test("an empty section says so in one line under its title", () => {
    const html = renderRun({ ...detail, run: { ...detail.run, inputs: {} } });
    expect(html).toContain("No documents generated by this run.");
    expect(html).not.toContain('data-k2-part="Empty"');
  });

  test("holds its place while it loads and offers no deeds", () => {
    const html = renderRun(null, "write");
    expect(html).toContain('data-k2-part="Loading"');
    expect(html).not.toContain("Technical details");
    expect(html).not.toContain('data-name="repeat"');
    expect(html).not.toContain('data-name="player-stop"');
  });

  test("documents: download all, more pages and a failed page stay reachable", () => {
    const html = renderToString(() =>
      createComponent(WorkflowRunDocumentsSection, {
        documents: { items: [], total: 101, hasMore: true, nextOffset: 100 },
        downloadingDocumentId: null,
        downloadingAll: true,
        loadingMore: true,
        loadMoreError: "Retry this page",
        onDownload: () => {},
        onDownloadAll: () => {},
        onLoadMore: () => {},
      }),
    );
    // a failed page says why where the section sums itself up
    expect(html).toContain("Retry this page");
    expect(html).toContain("Load more documents");
    // one download of every document, its kind in words where it is one (all PDF, all ZIP)
    expect(html).toContain(">All<");
  });
});
