export type ContactFormText = ReturnType<typeof contactFormMessages.resolve>["t"];

/** Localized default labels for freshly added contact-point rows. */
export const contactRowLabels = (t: ContactFormText): ContactRowLabels => ({
  email: t.rowLabelEmail,
  phone: t.rowLabelPhone,
  website: t.rowLabelWebsite,
  bank: t.rowLabelBank,
  address: t.rowLabelAddress,
});

const validationMessage: Record<ContactFormValidationKey, (t: ContactFormText) => string> = {
  websiteUrl: (t) => t.validationWebsiteUrl,
  addressFields: (t) => t.validationAddressFields,
  addressCountryCode: (t) => t.validationAddressCountryCode,
  bankFields: (t) => t.validationBankFields,
  birthdayFormat: (t) => t.validationBirthdayFormat,
};

/**
 * Maps a caught form error to display text: model validation errors resolve
 * through the catalog, other errors keep their (already localized) message.
 */
export const contactFormErrorMessage = (error: unknown, t: ContactFormText, fallback: string): string => {
  if (error instanceof ContactFormValidationError) return validationMessage[error.key](t);
  return error instanceof Error ? error.message : fallback;
};
