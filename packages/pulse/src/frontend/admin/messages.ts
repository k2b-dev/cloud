/** One fix hint per fixed check or request code; the CLI prints the same text as the page. */
export const storeFixHint = (code: StoreCheckCode | string, locale = "en"): string => {
  const t = storeMessages.resolve([locale]).t;
  const fixed: Record<string, string> = {
    UNREACHABLE: t.fixUnreachable,
    AUTH_FAILED: t.fixAuthFailed,
    VERSION_TOO_OLD: t.fixVersion,
    TOO_MANY_RIGHTS: t.fixTooManyRights,
    PASSWORD_REQUIRED: t.fixPasswordRequired,
    STORE_BUSY: t.fixBusy,
    INVALID_INPUT: t.fixInvalidInput,
    STORE_NOT_CONFIGURED: t.fixNotConfigured,
  };
  for (const right of REQUIRED_RIGHTS) fixed[`MISSING_RIGHT:${right}`] = t.fixRight({ right });
  if (fixed[code]) return fixed[code];
  if (code.startsWith("PROFILE_MISSING:")) return t.fixProfile({ profile: code.slice("PROFILE_MISSING:".length) });
  return t.fixRequest;
};
