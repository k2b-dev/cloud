export type PulseAdminMessages = ReturnType<typeof pulseAdminMessages.resolve>["t"];

/** The message for a fixed admin API code; unknown codes get the generic one. */
export const adminErrorText = (t: PulseAdminMessages, code: string): string =>
  ({
    INVALID_TARGET: t.errorInvalidTarget,
    TARGET_TOO_BROAD: t.errorTargetTooBroad,
    TARGET_EXISTS: t.errorTargetExists,
    NOT_FOUND: t.errorNotFound,
    STORE_NOT_CONFIGURED: t.errorStoreNotConfigured,
    STORE_UNAVAILABLE: t.errorStoreUnavailable,
    BASE_BUSY: t.errorBusy,
    INVALID_INPUT: t.errorInvalidInput,
    ACCESS_DENIED: t.errorAccessDenied,
  })[code] ?? t.actionFailed;
