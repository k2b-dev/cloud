export type HistoryMessages = ReturnType<typeof historyCatalog.resolve>["t"];
export type HistoryMessageKey = { [K in keyof HistoryMessages]: HistoryMessages[K] extends string ? K : never }[keyof HistoryMessages];

export const historyMessages = (locale: string) => historyCatalog.resolve([locale]).t;

export function useHistoryMessages() {
  const locale = useLocale();
  return () => historyMessages(locale());
}
