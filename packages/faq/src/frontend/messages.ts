export type FaqText = ReturnType<typeof faqMessages.resolve>["t"];

/** The FAQ catalog in the inherited `@k2b/ui` locale, for islands. */
export const useFaqMessages = () => {
  const locale = useLocale();
  return createMemo(() => faqMessages.resolve([locale()]).t);
};
