type Messages = ReturnType<typeof authMessages.resolve>["t"];
const scopeLabels = new Map<string, (t: Messages) => string>([
  ["read", (t) => t.scopeRead],
  ["write", (t) => t.scopeWrite],
  ["offline_access", (t) => t.scopeOffline],
  ["openid", (t) => t.scopeOpenId],
  ["profile", (t) => t.scopeProfile],
  ["email", (t) => t.scopeEmail],
  ["groups", (t) => t.scopeGroups],
  ["admin", (t) => t.scopeAdmin],
]);
/** Plain words for a requested OAuth scope, worded like the OAuth consent page. An unknown code stays as it is. */
export const scopeLabel = (scope: string, t: Messages): string => scopeLabels.get(scope)?.(t) ?? scope;
