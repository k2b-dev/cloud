#!/usr/bin/env bun
/** Render app environment/secrets from the registry and workspace; retain service configuration in scripts/templates. */
import { createHash } from "node:crypto";
import { appKeyFingerprint, deriveAppPublicKey } from "../packages/cloud/src/app-key";
import { env } from "../packages/cloud/src/config/env";
import fixtures from "./fixtures/development-app-keys.json";
import { appIds, devServiceName } from "./workspace";

const root = new URL("..", import.meta.url).pathname;
const appKeyFile = "CLOUD_APP_KEY_FILE";
if (!env.$specs.CLOUD_APP_KEY.secretFile || !env.$specs.CLOUD_CORE_INTERNAL_ORIGIN) throw new Error("App bootstrap registry is incomplete");
const appEnvironment = [appKeyFile, "CLOUD_CORE_INTERNAL_ORIGIN"];

export const renderAppDeployment = (template: string, development: boolean): string => {
  const ids = appIds(root).filter((id) => id !== "core" && id !== "gateway");
  const sections = template.split(/(?=^  (?:app-[a-z0-9-]+|gateway):\n)/m);
  const output = sections
    .map((section) => {
      const service = section.match(/^  (app-[a-z0-9-]+|gateway):\n/)?.[1];
      if (!service) return section;
      if (service === "gateway" || service === "app-core") {
        if (development && service === "app-core")
          section = section.replace(/(      APP_ID: core\n)/, "$1      CLOUD_DEV_APP_KEYS: true\n");
        return section;
      }
      const id = ids.find((id) => devServiceName(id) === service);
      if (!id) throw new Error(`Unknown deployment service ${service}`);
      if (/^    (?:secrets|depends_on):/m.test(section))
        throw new Error(`${service}: bootstrap secrets and dependencies are generator-owned`);
      const environment = development
        ? [
            "NODE_ENV: development",
            `APP_ID: ${id}`,
            ...appEnvironment.map((key) => `${key}: ${key === appKeyFile ? `/run/secrets/${id}.key` : "http://app-core:3000"}`),
          ]
        : appEnvironment.map((key) => `${key}: ${key === appKeyFile ? `/run/secrets/${id}.key` : "http://app-core:3000"}`);
      if (/^      CLOUD_(?:APP_KEY(?:_FILE)?|CORE_INTERNAL_ORIGIN):/m.test(section))
        throw new Error(`${service}: bootstrap environment is generator-owned`);
      const envLines = environment.map((line) => `      ${line}\n`).join("");
      if (/^    environment:\n/m.test(section)) section = section.replace(/^    environment:\n/m, `    environment:\n${envLines}`);
      else section = section.replace(/(^  [^\n]+\n)/, `$1    environment:\n${envLines}`);
      const generated = `    secrets:\n      - source: ${id}-app-key\n        target: ${id}.key\n    depends_on:\n      app-core:\n        condition: service_healthy\n`;
      return section.replace(/(^  [^\n]+\n)/, `$1${generated}`);
    })
    .join("");
  const secrets = ids.map((id) => `  ${id}-app-key:\n    file: ./${development ? ".local/dev-app-keys" : "secrets"}/${id}.key\n`).join("");
  return `# Generated by bun scripts/generate-app-deployments.ts; edit scripts/templates or the config registry.\n${output.trimEnd()}\n\nsecrets:\n${secrets}`;
};

/** Keep existing dev identities; derive public, deterministic fixtures for newly added workspace apps. */
export const renderDevelopmentKeys = async (ids: string[], existing = fixtures.keys) => {
  const keys = ids
    .filter((id) => id !== "core" && id !== "gateway")
    .sort()
    .map((appId) => {
      const current = existing.find((key) => key.appId === appId);
      if (current) return current;
      const digest = createHash("sha256").update(`cloud-public-development-app-key-v1:${appId}`).digest();
      const uuid = createHash("sha256").update(`cloud-public-development-key-id-v1:${appId}`).digest();
      uuid[6] = (uuid[6]! & 0x0f) | 0x40;
      uuid[8] = (uuid[8]! & 0x3f) | 0x80;
      const hex = uuid.toString("hex");
      return {
        appId,
        keyId: `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20, 32)}`,
        seed: digest.toString("base64url"),
      };
    });
  const publicKeys = await Promise.all(
    keys.map(async ({ seed, ...key }) => {
      const publicKey = await deriveAppPublicKey(seed);
      return { ...key, publicKey, fingerprint: await appKeyFingerprint(publicKey) };
    }),
  );
  return {
    fixtures: `${JSON.stringify({ warning: fixtures.warning, keys }, null, 2)}\n`,
    publicKeys: `// Generated by bun scripts/generate-app-deployments.ts. Public keys only; dev-only private fixtures live under scripts/fixtures.\nexport const DEVELOPMENT_INSTALLATION_ID = "c10dd0c0-0000-4000-a000-000000000001";\nexport const DEVELOPMENT_APP_KEYS = ${"[\n" + publicKeys.map((key) => `  {\n    appId: ${JSON.stringify(key.appId)},\n    keyId: ${JSON.stringify(key.keyId)},\n    publicKey: ${JSON.stringify(key.publicKey)},\n    fingerprint: ${JSON.stringify(key.fingerprint)},\n  },`).join("\n") + "\n]"} as const;\nexport const isDevelopmentPublicKey = (publicKey: string): boolean => DEVELOPMENT_APP_KEYS.some((key) => key.publicKey === publicKey);\n`,
  };
};

if (import.meta.main) {
  if (process.argv.includes("--help")) {
    console.log(
      "Usage: bun scripts/generate-app-deployments.ts [--check]\nRender Compose files from scripts/templates, the workspace and environment registry.",
    );
  } else {
    if (process.argv.slice(2).some((arg) => arg !== "--check")) throw new Error("Use --help for usage");
    let stale = false;
    for (const development of [false, true]) {
      const name = `compose.${development ? "dev" : "prod"}.yml`;
      const content = renderAppDeployment(await Bun.file(`${root}scripts/templates/${name}`).text(), development);
      const current = await Bun.file(`${root}${name}`).text();
      if (content === current) continue;
      if (process.argv.includes("--check")) {
        console.error(`${name} is stale; run bun scripts/generate-app-deployments.ts`);
        stale = true;
      } else await Bun.write(`${root}${name}`, content);
    }
    const development = await renderDevelopmentKeys(appIds(root));
    for (const [path, content] of [
      ["scripts/fixtures/development-app-keys.json", development.fixtures],
      ["packages/cloud/src/runtime/development-keys.ts", development.publicKeys],
    ] as const) {
      if ((await Bun.file(`${root}${path}`).text()) === content) continue;
      if (process.argv.includes("--check")) {
        console.error(`${path} is stale; run bun scripts/generate-app-deployments.ts`);
        stale = true;
      } else await Bun.write(`${root}${path}`, content);
    }
    if (stale) process.exit(1);
  }
}
